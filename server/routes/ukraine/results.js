/**
 * results.js — Ukraine FBMC web results (plan task 2.3).
 *
 * Serves the slim web output dir that modelRunner.js copies back from the
 * Windows compute box (or that the local worker writes directly):
 * PyPSA-Ukraine/results/web_runs/<run_id>/ containing the web-profile files
 * (market_prices.csv, load_shedding.csv, net_positions.csv,
 * generation_mix.csv, cnec_binding.csv, kpis.json, run_meta.json,
 * run_signature.json, manifest.json — plan D3).
 *
 * Endpoints:
 * - GET /runs                      : list available run dirs + KPI summaries
 * - GET /list?run=<run_id>         : one run's files + parsed summary docs
 * - GET /kpis?run=<run_id>         : parsed kpis.json
 * - GET /meta?run=<run_id>         : parsed run_meta.json
 * - GET /download?run=..&file=..   : serve one file (attachment; ?inline=1
 *                                    serves it inline for fetch/plotting)
 *
 * Run ids are generated by buildRunId() (safe charset); paths are resolved
 * strictly inside the runs root (no traversal).
 */

import express from "express";
import fs from "fs";
import path from "path";
import { MODEL_KEY, RUNS_ROOT } from "./shared.js";

const router = express.Router();

const SUMMARY_FILES = {
  kpis: "kpis.json",
  meta: "run_meta.json",
  signature: "run_signature.json",
};

function resolveRunDir(runId) {
  const key = String(runId || "").trim();
  if (!/^[\w.-]+$/.test(key)) return null;
  const runDir = path.resolve(RUNS_ROOT, key);
  if (runDir !== RUNS_ROOT && runDir.startsWith(RUNS_ROOT + path.sep) && fs.existsSync(runDir)) {
    return runDir;
  }
  return null;
}

function parseJsonFile(filePath) {
  try {
    return JSON.parse(fs.readFileSync(filePath, "utf8"));
  } catch {
    return null;
  }
}

function buildRunSummary(runDir, runId) {
  const summary = {
    runId,
    files: [],
    kpis: null,
    meta: null,
    signature: null,
    submittedAt: null,
    runName: null,
  };

  for (const entry of fs.readdirSync(runDir, { withFileTypes: true })) {
    if (!entry.isFile()) continue;
    summary.files.push(entry.name);
  }
  summary.files.sort();

  summary.kpis = parseJsonFile(path.join(runDir, SUMMARY_FILES.kpis));
  summary.meta = parseJsonFile(path.join(runDir, SUMMARY_FILES.meta));
  summary.signature = parseJsonFile(path.join(runDir, SUMMARY_FILES.signature));
  summary.submittedAt = summary.signature?.submittedAt || summary.meta?.submitted_at || null;
  summary.runName = summary.signature?.runName || null;

  return summary;
}

// List every finished run dir (skipping the _work scratch root)
router.get("/runs", (req, res) => {
  try {
    if (!fs.existsSync(RUNS_ROOT)) {
      return res.json({ runs: [] });
    }

    const runs = [];
    for (const entry of fs.readdirSync(RUNS_ROOT, { withFileTypes: true })) {
      if (!entry.isDirectory() || entry.name.startsWith("_")) continue;
      const runDir = path.join(RUNS_ROOT, entry.name);
      try {
        runs.push({ ...buildRunSummary(runDir, entry.name), mtimeMs: fs.statSync(runDir).mtimeMs });
      } catch (err) {
        console.error(`[ukraine] Skipping unreadable run dir ${entry.name}:`, err.message);
      }
    }

    runs.sort((a, b) => b.mtimeMs - a.mtimeMs);
    return res.json({ runs });
  } catch (err) {
    console.error(err);
    return res.status(500).json({ error: "Failed to list runs", details: err.message });
  }
});

// One run's file list + parsed summary docs
router.get("/list", (req, res) => {
  const runDir = resolveRunDir(req.query.run);
  if (!runDir) {
    return res.status(404).json({ error: "Run not found" });
  }
  try {
    return res.json(buildRunSummary(runDir, path.basename(runDir)));
  } catch (err) {
    return res.status(500).json({ error: "Failed to read run", details: err.message });
  }
});

function serveParsedJson(docName, fileName) {
  return (req, res) => {
    const runDir = resolveRunDir(req.query.run);
    if (!runDir) {
      return res.status(404).json({ error: "Run not found" });
    }
    const parsed = parseJsonFile(path.join(runDir, fileName));
    if (!parsed) {
      return res.status(404).json({ error: `No ${docName} found for this run` });
    }
    return res.json(parsed);
  };
}

router.get("/kpis", serveParsedJson("kpis.json", SUMMARY_FILES.kpis));
router.get("/meta", serveParsedJson("run_meta.json", SUMMARY_FILES.meta));

// Download (or inline) one file from a run dir
router.get("/download", (req, res) => {
  const runDir = resolveRunDir(req.query.run);
  const fileName = String(req.query.file || "").trim();

  if (!runDir) {
    return res.status(404).json({ error: "Run not found" });
  }
  if (!fileName || fileName !== path.basename(fileName)) {
    return res.status(400).json({ error: "Invalid file parameter" });
  }

  const fullPath = path.join(runDir, fileName);
  if (!fs.existsSync(fullPath) || !fs.statSync(fullPath).isFile()) {
    return res.status(404).json({ error: "File not found" });
  }

  if (String(req.query.inline || "") === "1") {
    res.setHeader("Content-Disposition", `inline; filename="${fileName}"`);
    return res.sendFile(fullPath);
  }

  return res.download(fullPath, fileName, (err) => {
    if (err) {
      console.error("Download error:", err);
      if (!res.headersSent) {
        res.status(500).json({ error: "Error sending file" });
      }
    }
  });
});

export default router;
